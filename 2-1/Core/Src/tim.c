void KEY_Tick(void)
{
  static uint32_t cnt,tim;
  cnt ++;
  if (tim >0)
  {
    tim--;
  }
  if (cnt > 20)
  {
    cnt = 0;
    static uint8_t pre,cur,s;
    cur = HAL_GPIO_ReadPin(KEY_GPIO_Port,KEY_Pin);
    if (s == 0)
    {
      if (pre == 1 && cur == 0)
      {
        s = 1;
        tim = 1000;
      }
    }
    if (s == 1)
    {
      if (pre == 0 && cur == 1)
      {
        if (LED_Flag == 0)
        {
           HAL_GPIO_TogglePin(LED_GPIO_Port,LED_Pin);
        }
        s = 0;
      }
      else if (tim == 0)
      {
        
        if (LED_Flag == 0)
        {
          LED_Flag = 1;
        }
        else
        {
          LED_Flag = 0;
        }                                                      
        HAL_GPIO_WritePin(LED_GPIO_Port,LED_Pin,GPIO_PIN_RESET);
        s = 0;
      }
    }
    pre = cur;
  }
}

void LED_ON(void)
{
  static uint32_t p,c;
  c = HAL_GetTick();
  if (LED_Flag == 1)
  {
    if (c - p > 100)
    {
      HAL_GPIO_TogglePin(LED_GPIO_Port,LED_Pin);
      p = c;
    }
  }
}
